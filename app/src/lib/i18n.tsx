const DICTS: Record<Lang, Record<Key, string>> = { zh, en };

const I18nCtx = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key) => string;
  tf: (k: Key, vars: Record<string, string | number>) => string;
}>({ lang: 'zh', setLang: () => {}, t: (k) => zh[k], tf: (k) => zh[k] });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(
    () => (localStorage.getItem('mai2srt.lang') as Lang) || 'zh',
  );
  const setLang = useCallback((l: Lang) => {
    localStorage.setItem('mai2srt.lang', l);
    setLangState(l);
  }, []);
  const t = useCallback((k: Key) => DICTS[lang][k] ?? k, [lang]);
  /** t with {placeholder} interpolation */
  const tf = useCallback(
    (k: Key, vars: Record<string, string | number>) => {
      let s: string = DICTS[lang][k] ?? k;
      for (const [kk, vv] of Object.entries(vars)) {
        s = s.replaceAll(`{${kk}}`, String(vv));
      }
      return s;
    },
    [lang],
  );
  return <I18nCtx.Provider value={{ lang, setLang, t, tf }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
